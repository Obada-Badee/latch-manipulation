#!/usr/bin/env python3
"""Check a generated dataset BEFORE training on it.

    python3 validate.py --dataset ~/synth_obb

The plan calls the label projection the highest technical risk in the whole
project, and the reason is that a systematic projection error is invisible
downstream: the detector trains to a low loss against consistent labels, then
produces confident boxes that back-project to the wrong place. The symptom
appears three layers later as "the IK is off" or "the grasp keeps missing".

So this does four things, in increasing order of what they can catch:

1. **Structural checks.** Label files parse, class ids are in range, coordinates
   are normalised, and every frame's label count matches the ground truth.
   Catches format mistakes; proves nothing about geometry.

2. **Overlay images.** Draw each label back onto the image it was generated for.
   This is the check that actually catches a wrong projection, because a human
   can see instantly whether the boxes sit on the objects. Nothing else in the
   pipeline can substitute for looking.

3. **Back-projection error.** Take each label's OBB centre, back-project it the
   way world_model will at runtime, and compare against the known true grasp
   target. This measures the *deployed* accuracy of perception on real rendered
   frames, not on synthetic poses - which is the number the grasp budget in
   scene.py depends on.

4. **Colour recovery.** Run the same HSV logic world_model uses on the real
   pixels and check it agrees with the colour the object was actually spawned
   with. A colour classifier that works on paper and fails on rendered pixels
   would break every "the yellow cube" instruction while leaving detection
   perfect - and would look like an LLM grounding failure.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import sys
from collections import Counter, defaultdict
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

from labeler import (GRASP_CLEARANCE_MM, label_coverage,     # noqa: E402
                     overlap_fraction)
from objects import CLASS_NAMES                              # noqa: E402
from yolov8_obb.projection import (CAMERA, DEFAULT_CENTROID_Z,  # noqa: E402
                                  OBJECT_CENTROID_Z, obb_axes_px, obb_center)

#: BGR, for the overlay. Distinct per class and readable on wood.
CLASS_COLOR = {"cube": (60, 220, 60), "cylinder": (255, 140, 0),
               "bolt": (0, 90, 255)}


def load_ground_truth(root: str) -> List[dict]:
    path = os.path.join(root, "ground_truth.jsonl")
    if not os.path.isfile(path):
        raise SystemExit(f"no ground_truth.jsonl in {root} - was the dataset "
                         f"generated by generate.py?")
    with open(path, encoding="utf-8") as fh:
        return [json.loads(l) for l in fh if l.strip()]


# --------------------------------------------------------------------------
# 1. structural
# --------------------------------------------------------------------------

def frame_stem(rec: dict) -> str:
    """The label/overlay stem for a ground-truth record.

    Derived from the recorded image path rather than reformatted from a frame
    number. The number-formatting version only worked for generate.py's
    `%06d.png` naming, which quietly made this validator unusable on the live
    hard-negative set (`neg_00001.png`) - the one dataset built from *read*
    ground truth, i.e. the one with the most ways to be wrong and the most need
    for checking. Falls back to the number when a record predates the field.
    """
    image = rec.get("image")
    if image:
        return os.path.splitext(os.path.basename(image))[0]
    return f"{rec['frame']:06d}"


def check_structure(root: str, gt: List[dict]) -> List[str]:
    problems: List[str] = []
    for rec in gt:
        stem = frame_stem(rec)
        img = os.path.join(root, rec["image"])
        lbl = os.path.join(root, "labels", rec["split"], stem + ".txt")
        if not os.path.isfile(img):
            problems.append(f"frame {stem}: image missing at {rec['image']}")
            continue
        if not os.path.isfile(lbl):
            problems.append(f"frame {stem}: label file missing")
            continue
        lines = [l for l in open(lbl, encoding="utf-8").read().splitlines() if l.strip()]
        if len(lines) != len(rec["objects"]):
            problems.append(f"frame {stem}: {len(lines)} label lines but "
                            f"{len(rec['objects'])} ground-truth objects")
        for k, line in enumerate(lines):
            parts = line.split()
            if len(parts) != 9:
                problems.append(f"frame {stem} line {k}: {len(parts)} fields, want 9")
                continue
            cid = int(parts[0])
            if not 0 <= cid < len(CLASS_NAMES):
                problems.append(f"frame {stem} line {k}: class id {cid} out of range")
            vals = [float(x) for x in parts[1:]]
            if not all(0.0 <= v <= 1.0 for v in vals):
                problems.append(f"frame {stem} line {k}: coordinate outside [0,1]")
            # A degenerate box trains the model to predict nonsense.
            xs, ys = vals[0::2], vals[1::2]
            w = (max(xs) - min(xs)) * CAMERA.width
            h = (max(ys) - min(ys)) * CAMERA.height
            if w < 3 or h < 3:
                problems.append(f"frame {stem} line {k}: box is {w:.1f}x{h:.1f} px")
    return problems


# --------------------------------------------------------------------------
# 2. overlay
# --------------------------------------------------------------------------

def write_overlays(root: str, gt: List[dict], out_dir: str, count: int) -> List[str]:
    import cv2

    os.makedirs(out_dir, exist_ok=True)
    # Spread the samples across the run rather than taking the first N, so a
    # drift that only appears later is not missed.
    step = max(1, len(gt) // max(count, 1))
    picked = gt[::step][:count]
    written = []

    for rec in picked:
        img = cv2.imread(os.path.join(root, rec["image"]))
        if img is None:
            continue
        vis = img.copy()
        for obj in rec["objects"]:
            pts = np.array(obj["corners_px"], dtype=np.int32)
            color = CLASS_COLOR.get(obj["class"], (255, 255, 255))
            cv2.polylines(vis, [pts], isClosed=True, color=color, thickness=1)
            # Mark the OBB centre and the true grasp target. If the projection is
            # right these coincide for cubes/cylinders and differ along the shaft
            # for bolts - visible confirmation of the reference-point distinction.
            u, v = obb_center(obj["corners_px"])
            cv2.drawMarker(vis, (int(round(u)), int(round(v))), color,
                           cv2.MARKER_CROSS, 7, 1)
            gx, gy = obj["grasp_target_link0"]
            tu, tv = CAMERA.link0_to_pixel(gx, gy, OBJECT_CENTROID_Z.get(
                obj["class"], DEFAULT_CENTROID_Z))
            cv2.drawMarker(vis, (int(round(tu)), int(round(tv))), (255, 255, 255),
                           cv2.MARKER_TILTED_CROSS, 6, 1)
            cv2.putText(vis, f"{obj['class'][:3]}/{obj['color'][:1]}",
                        (int(pts[:, 0].min()), max(9, int(pts[:, 1].min()) - 3)),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.32, color, 1, cv2.LINE_AA)

        # Side by side: raw render on the left, labelled on the right. Judging a
        # box's fit is much easier with the unannotated pixels next to it.
        pair = np.hstack([img, vis])
        path = os.path.join(out_dir, f"overlay_{frame_stem(rec)}.png")
        cv2.imwrite(path, pair)
        written.append(path)

    # One contact sheet, so the whole sample can be judged in a single look.
    thumbs = [cv2.resize(cv2.imread(p), (480, 180)) for p in written[:24]]
    if thumbs:
        cols = 3
        rows = [np.hstack(thumbs[i:i + cols])
                for i in range(0, len(thumbs) - len(thumbs) % cols, cols)]
        if rows:
            sheet = os.path.join(out_dir, "contact_sheet.png")
            cv2.imwrite(sheet, np.vstack(rows))
            written.append(sheet)
    return written


# --------------------------------------------------------------------------
# 3. back-projection error
# --------------------------------------------------------------------------

def check_backprojection(gt: List[dict]) -> Tuple[Dict[str, np.ndarray], List[str]]:
    """Error between what world_model would report and the true grasp target."""
    errs: Dict[str, List[float]] = defaultdict(list)
    for rec in gt:
        for obj in rec["objects"]:
            u, v = obb_center(obj["corners_px"])
            plane = OBJECT_CENTROID_Z.get(obj["class"], DEFAULT_CENTROID_Z)
            ix, iy = CAMERA.pixel_to_link0(u, v, plane)
            gx, gy = obj["grasp_target_link0"]
            errs[obj["class"]].append(math.hypot(ix - gx, iy - gy) * 1000.0)

    problems: List[str] = []
    out: Dict[str, np.ndarray] = {}
    for cls, vals in errs.items():
        a = np.array(vals)
        out[cls] = a
        limit = GRASP_CLEARANCE_MM.get(cls, 10.0)
        if a.max() > limit:
            problems.append(
                f"{cls}: worst back-projection error {a.max():.1f} mm exceeds the "
                f"{limit:.0f} mm of jaw clearance. Perception cannot place the "
                f"gripper accurately enough to grasp - fix "
                f"projection.OBJECT_CENTROID_Z before training.")
    return out, problems


# --------------------------------------------------------------------------
# 3b. image/label pairing
# --------------------------------------------------------------------------

def check_pairing(root: str, gt: List[dict], limit: int = 500
                  ) -> Tuple[np.ndarray, List[str]]:
    """Does each image really show the scene its labels describe?

    A regression test for a bug that shipped once. Speeding the generator up 10x
    (CLI service calls -> a persistent transport node) meant frames started
    arriving faster than the render pipeline delivered them, so ~22% of frames
    showed the *previous* scene while carrying the new scene's labels. Geometry
    was perfect; only the pairing was wrong. It presented as a broken colour
    classifier.

    generate.py now verifies this per frame and retries, so this should come back
    clean. It stays here because the failure was invisible to every other check
    and cost nothing to detect once the right question was asked.
    """
    import cv2

    covs: List[float] = []
    problems: List[str] = []
    step = max(1, len(gt) // limit)
    for rec in gt[::step]:
        img = cv2.imread(os.path.join(root, rec["image"]))
        if img is None:
            continue
        for obj in rec["objects"]:
            # No global background: label_coverage compares each box against a
            # ring of its own surroundings. See labeler.ring_background.
            covs.append(label_coverage(img, obj["corners_px"]))
    arr = np.array(covs) if covs else np.zeros(0)
    if arr.size:
        stale = float((arr < 0.15).mean())
        if stale > 0.01:
            problems.append(
                f"{stale * 100:.1f}% of labels sit on background - the images and "
                f"labels are not paired. Frames are being captured before the "
                f"teleport takes effect; see labeler.label_coverage.")
    return arr, problems


# --------------------------------------------------------------------------
# 4. colour recovery
# --------------------------------------------------------------------------

def check_colors(root: str, gt: List[dict], limit: int = 300
                 ) -> Tuple[Counter, List[str]]:
    """Does world_model's HSV logic recover the colour each object was spawned in?

    Calls ``world_model.classify_color`` itself - the exact function the running
    robot uses. An earlier version of this check reimplemented the band lookup
    here and reported 100%, which proved only that two pieces of code written by
    the same hand agreed with each other. If world_model cannot be imported
    (it needs rclpy and the message package) the check is skipped loudly rather
    than silently passing.
    """
    import cv2

    try:
        sys.path.insert(0, os.path.join(
            os.path.dirname(os.path.dirname(HERE)), "src", "yolov8_obb", "scripts"))
        from world_model import classify_color     # type: ignore  # noqa
    except Exception as e:                          # noqa: BLE001
        return Counter(), [f"SKIPPED colour check: could not import world_model "
                           f"({type(e).__name__}: {e}). The colour path is then "
                           f"UNVERIFIED - run this inside the ROS environment."]

    confusion: Counter = Counter()
    for rec in gt[:limit]:
        img = cv2.imread(os.path.join(root, rec["image"]))
        if img is None:
            continue
        for obj in rec["objects"]:
            confusion[(obj["color"], classify_color(img, obj["corners_px"]))] += 1
    return confusion, []


# --------------------------------------------------------------------------

def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", default=os.path.expanduser("~/synth_obb"))
    ap.add_argument("--overlays", type=int, default=24)
    ap.add_argument("--skip-colors", action="store_true")
    args = ap.parse_args(argv)

    root = args.dataset
    gt = load_ground_truth(root)
    n_obj = sum(len(r["objects"]) for r in gt)
    print(f"dataset: {root}")
    print(f"  {len(gt)} frames, {n_obj} labelled instances "
          f"({n_obj / max(len(gt), 1):.1f} per frame)")

    splits = Counter(r["split"] for r in gt)
    print(f"  split: " + ", ".join(f"{k} {v}" for k, v in sorted(splits.items())))

    cls_counts = Counter(o["class"] for r in gt for o in r["objects"])
    col_counts = Counter(o["color"] for r in gt for o in r["objects"])
    print(f"  classes: " + ", ".join(f"{c} {cls_counts[c]}" for c in CLASS_NAMES))
    print(f"  colours: " + ", ".join(f"{k} {v}" for k, v in sorted(col_counts.items())))

    fatal: List[str] = []
    warn: List[str] = []

    # --- 1
    print("\n[1/4] structure")
    problems = check_structure(root, gt)
    if problems:
        print(f"  {len(problems)} problems, first 10:")
        for p in problems[:10]:
            print(f"    - {p}")
        fatal.extend(problems[:10])
    else:
        print("  all label files parse, all coordinates normalised, counts match")

    # --- 2
    print(f"\n[2/4] overlays")
    try:
        written = write_overlays(root, gt, os.path.join(root, "validation"),
                                args.overlays)
        print(f"  wrote {len(written)} images to {os.path.join(root, 'validation')}")
        print(f"  LOOK AT THESE before training. Left half is the raw render, "
              f"right half has the labels.")
        print(f"  Boxes must sit tightly on the objects, including the ones near "
              f"the frame edges where perspective is strongest.")
    except Exception as e:                           # noqa: BLE001
        warn.append(f"overlay generation failed: {type(e).__name__}: {e}")
        print(f"  FAILED: {e}")

    # --- 3
    print("\n[3/4] back-projection accuracy (what world_model will report)")
    errs, problems = check_backprojection(gt)
    print("  class      n      mean    p95   worst   clearance   verdict")
    for cls in CLASS_NAMES:
        if cls not in errs:
            continue
        a = errs[cls]
        limit = GRASP_CLEARANCE_MM.get(cls, 10.0)
        ok = "ok" if a.max() <= limit else "TOO LARGE"
        print(f"  {cls:<9} {len(a):>5}   {a.mean():5.1f}  {np.percentile(a, 95):5.1f}  "
              f"{a.max():5.1f}   {limit:>6.0f} mm   {ok}")
    fatal.extend(problems)

    # --- 3b
    print("\n[3b] image/label pairing (does each image show its own scene?)")
    covs, problems = check_pairing(root, gt)
    if covs.size:
        print(f"  label coverage over {covs.size} sampled instances: "
              f"p1 {np.percentile(covs, 1):.2f}  p50 {np.percentile(covs, 50):.2f}  "
              f"mean {covs.mean():.2f}")
        print(f"  on background (<0.15): {(covs < 0.15).mean() * 100:.2f}%   "
              f"on an object (>0.35): {(covs > 0.35).mean() * 100:.2f}%")
    fatal.extend(problems)

    # --- 4
    if args.skip_colors:
        print("\n[4/4] colour recovery: skipped")
    else:
        print("\n[4/4] colour recovery (world_model's HSV logic on real pixels)")
        confusion, notes = check_colors(root, gt)
        for n in notes:
            print(f"  {n}")
            warn.append(n)
        if confusion:
            truths = sorted({t for t, _ in confusion})
            gots = sorted({g for _, g in confusion})
            head = "".join(f"{g[:6]:>8}" for g in gots)
            print(f"  {'spawned':<10}{head}     accuracy")
            total_ok = total = 0
            for t in truths:
                row = "".join(f"{confusion[(t, g)]:>8}" for g in gots)
                n = sum(confusion[(t, g)] for g in gots)
                ok = confusion[(t, t)] if (t, t) in confusion else 0
                total_ok += ok
                total += n
                acc = ok / n if n else 0.0
                print(f"  {t:<10}{row}     {acc * 100:5.1f}%")
                if acc < 0.90 and n >= 20:
                    fatal.append(f"colour {t!r} is recovered only {acc * 100:.0f}% "
                                 f"of the time - 'the {t} cube' will ground to the "
                                 f"wrong object")
            print(f"  overall colour accuracy: "
                  f"{total_ok / max(total, 1) * 100:.1f}% over {total} instances")

    # --- verdict
    print("\n" + "=" * 68)
    if fatal:
        print(f"NOT READY TO TRAIN - {len(fatal)} blocking problems:")
        for f in fatal[:12]:
            print(f"  - {f}")
        return 1
    if warn:
        print(f"{len(warn)} warnings:")
        for w in warn:
            print(f"  - {w}")
    print("structural and numeric checks passed.")
    print("Now open the overlay images. The numbers cannot tell you whether the")
    print("boxes are on the objects - only looking can.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
