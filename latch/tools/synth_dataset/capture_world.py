"""Generate the SDF world the dataset is captured in.

Why a purpose-built world rather than the real cell
--------------------------------------------------
The real world (worlds/arm_on_the_table.sdf) is brought up by a ROS launch file
that also starts MoveIt, three controllers, and the arm. None of that is needed
to render a frame, all of it is slow to start, and the arm's controllers fight
the teleporting this generator does. So the capture world keeps exactly the
things the camera sees and nothing else:

  * the same table model, at the same pose
  * the same camera, at the same extrinsics and intrinsics, generated from the
    same numbers projection.py uses - so a label computed here is valid in the
    real cell
  * the two bins, as unlabelled background (see objects.py for why)
  * the object pool, parked off-camera until a frame wants them

What is deliberately missing, and the consequence
-------------------------------------------------
**The arm.** In the live cell the robot is in frame - the camera sits at link0
(0.20, 0.60, 0.70) and link0 itself is inside the frustum - so a detector
trained here has never seen the arm and is free to invent a detection on it.

That is a real gap, and the honest fix is not to model the arm here (it needs
the xacro, ros2_control, and a controller stack to hold a pose) but to run the
same generator against the live cell for a smaller set of frames, where the arm
is present and parked. generate.py takes --world for exactly that reason. Doing
the bulk here first is the cheap way round: if the projection math is wrong,
finding out costs 30 seconds rather than a full bring-up.

The near clip is 0.02 m and the camera looks straight down from 0.70 m above
link0's plane, so nothing on the table is clipped.
"""

from __future__ import annotations

import os
from typing import List

from objects import BINS, TABLE_TOP_WORLD_Z, PoolItem, _bin_sdf, build_pool

# The camera's pose in the *world* frame, derived rather than copied:
#   panda_link0 sits at world (0.05, 0.00, 1.02)      [projection.LINK0_IN_WORLD]
#   camera_link sits at link0 (0.20, 0.60, 0.70)      [config/panda.urdf.xacro:13]
# The pi/2 pitch turns the camera's +X optical axis to point straight down.
# These are imported, not retyped, so the capture geometry cannot drift from the
# geometry the labeller assumes.
import sys

_REPO = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
if os.path.join(_REPO, "src", "yolov8_obb") not in sys.path:
    sys.path.insert(0, os.path.join(_REPO, "src", "yolov8_obb"))
from yolov8_obb.projection import CAMERA, LINK0_IN_WORLD, link0_to_world  # noqa: E402

WORLD_NAME = "synth_capture"

#: Table pose, copied from arm_on_the_table.sdf (`<pose>0.29 0 0 0 0 1.5708</pose>`).
TABLE_POSE = "0.29 0 0 0 0 1.5708"


def camera_model_sdf() -> str:
    """A static model carrying the same camera sensor the robot does.

    Intrinsics come from projection.CAMERA so the two cannot disagree; the
    remaining sensor settings (clip planes, noise, format, rate) are copied from
    robot_description/urdf/camera/camera.gazebo. The noise is kept: it is what
    the detector will see at inference, and training on cleaner images than
    deployment provides is a quiet way to lose accuracy.

    The camera_link visual mesh is *not* included - in the live cell it sits at
    the camera's own origin, inside the near clip plane, so it contributes
    nothing to the image.
    """
    cx, cy, cz = link0_to_world(*CAMERA.origin)
    return f"""    <model name="capture_camera">
      <static>true</static>
      <pose>{cx} {cy} {cz} 0 1.5707963267948966 0</pose>
      <link name="camera_link">
        <sensor name="camera_sensor" type="camera">
          <update_rate>30.0</update_rate>
          <topic>/image_raw</topic>
          <always_on>1</always_on>
          <camera name="robot_camera">
            <horizontal_fov>{CAMERA.hfov}</horizontal_fov>
            <image>
              <width>{CAMERA.width}</width>
              <height>{CAMERA.height}</height>
              <format>R8G8B8</format>
            </image>
            <clip><near>0.02</near><far>300</far></clip>
            <noise>
              <type>gaussian</type>
              <mean>0.0</mean>
              <stddev>0.007</stddev>
            </noise>
          </camera>
        </sensor>
      </link>
    </model>"""


def build_world(pool: List[PoolItem] | None = None) -> str:
    pool = pool if pool is not None else build_pool()
    models = "\n".join("    " + p.sdf().replace("\n", "\n    ") for p in pool)
    bins = "\n".join("    " + _bin_sdf(n, x, y, c) for n, x, y, c in BINS)

    return f"""<?xml version="1.0" ?>
<!--
  GENERATED by tools/synth_dataset/capture_world.py - do not edit by hand.
  Regenerate with:  python3 capture_world.py
  Rationale for every choice here is in that file's docstring.
-->
<sdf version="1.9">
  <world name="{WORLD_NAME}">
    <!-- Physics is present because the Sensors system needs a stepping world,
         but nothing here is dynamic: every object is <static>, so a commanded
         pose IS the ground-truth pose and there is no settling to wait for. -->
    <physics name="quick" type="ignored">
      <max_step_size>0.004</max_step_size>
      <real_time_factor>0</real_time_factor>
    </physics>

    <plugin filename="gz-sim-physics-system"
            name="gz::sim::systems::Physics"/>
    <!-- UserCommands provides /world/{WORLD_NAME}/set_pose, which is how
         objects are teleported between frames. -->
    <plugin filename="gz-sim-user-commands-system"
            name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system"
            name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system"
            name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>

    <!-- Shadows off, matching arm_on_the_table.sdf's <scene><shadows>0. -->
    <scene>
      <shadows>0</shadows>
      <ambient>0.4 0.4 0.4 1</ambient>
      <background>0.7 0.7 0.7 1</background>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
          <material>
            <ambient>0.3 0.3 0.3 1</ambient>
            <diffuse>0.5 0.5 0.5 1</diffuse>
          </material>
        </visual>
      </link>
    </model>

    <model name="table">
      <static>true</static>
      <include><uri>model://table</uri></include>
      <pose>{TABLE_POSE}</pose>
    </model>

{camera_model_sdf()}

    <!-- ============ destination bins: background, never labelled ========== -->
{bins}

    <!-- ============ object pool, parked off-camera ======================== -->
{models}
  </world>
</sdf>
"""


DEFAULT_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "generated", "synth_capture.sdf")


def write_world(path: str = DEFAULT_OUT) -> str:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(build_world())
    return path


def _self_test() -> int:
    import xml.etree.ElementTree as ET

    failures = []
    xml = build_world()

    try:
        root = ET.fromstring(xml)
    except ET.ParseError as e:
        print(f"FAILED: generated world is not valid XML: {e}")
        return 1

    world = root.find("world")
    if world is None or world.get("name") != WORLD_NAME:
        failures.append("world element missing or misnamed")

    models = {m.get("name") for m in world.findall("model")}
    pool = build_pool()
    for p in pool:
        if p.model_name not in models:
            failures.append(f"pool model {p.model_name} missing from the world")
    for n, _, _, _ in BINS:
        if n not in models:
            failures.append(f"bin {n} missing from the world")
    for required in ("table", "capture_camera", "ground_plane"):
        if required not in models:
            failures.append(f"{required} missing from the world")
    print(f"  world declares {len(models)} models "
          f"({len(pool)} pool + {len(BINS)} bins + 3 fixtures)")

    # Every model must be static: the whole ground-truth argument rests on it.
    for m in world.findall("model"):
        st = m.find("static")
        if st is None or st.text.strip() not in ("true", "1"):
            failures.append(f"model {m.get('name')} is not static - a commanded "
                            f"pose would stop being the ground-truth pose")

    # The camera must sit exactly where projection.py thinks it does, or every
    # label in the dataset is offset by the difference.
    cam = world.find("./model[@name='capture_camera']")
    pose = [float(t) for t in cam.find("pose").text.split()]
    want = link0_to_world(*CAMERA.origin)
    for i, axis in enumerate("xyz"):
        if abs(pose[i] - want[i]) > 1e-9:
            failures.append(f"camera {axis} is {pose[i]} but projection.py "
                            f"assumes {want[i]}")
    if abs(pose[4] - 1.5707963267948966) > 1e-9 or abs(pose[3]) > 1e-12 or abs(pose[5]) > 1e-12:
        failures.append(f"camera rpy is {pose[3:]} - must be (0, pi/2, 0) so the "
                        f"optical axis points straight down")
    print(f"  camera at world ({pose[0]:.2f}, {pose[1]:.2f}, {pose[2]:.2f}), "
          f"pitch {pose[4]:.4f} rad  = link0 {CAMERA.origin}")

    sensor = cam.find(".//sensor")
    fov = float(sensor.find("./camera/horizontal_fov").text)
    w = int(sensor.find("./camera/image/width").text)
    h = int(sensor.find("./camera/image/height").text)
    if (fov, w, h) != (CAMERA.hfov, CAMERA.width, CAMERA.height):
        failures.append(f"camera intrinsics ({fov}, {w}x{h}) disagree with "
                        f"projection.CAMERA ({CAMERA.hfov}, "
                        f"{CAMERA.width}x{CAMERA.height})")
    print(f"  intrinsics hfov {fov} at {w}x{h} -> fx {CAMERA.fx:.4f}")

    if abs(LINK0_IN_WORLD[2] + CAMERA.origin[2] - pose[2]) > 1e-9:
        failures.append("camera world z is not link0 z + camera link0 z")

    # The Sensors system must be present, or the camera never renders and the
    # generator waits forever for a frame that will not arrive.
    plugins = {p.get("filename") for p in world.findall("plugin")}
    for required in ("gz-sim-sensors-system", "gz-sim-user-commands-system"):
        if required not in plugins:
            failures.append(f"world is missing the {required} plugin")

    print()
    if failures:
        print(f"FAILED ({len(failures)}):")
        for f in failures:
            print(f"  - {f}")
        return 1
    path = write_world()
    print(f"all capture-world self-tests passed; wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(_self_test())
